//! Запуск вспомогательных утилит без консольного окна.
//!
//! В release пикер собран как `windows_subsystem = "windows"` и своей консоли
//! не имеет. Когда такой процесс поднимает консольную программу, Windows
//! выделяет ей новую консоль — с окном, которое всплывает поверх всего и
//! забирает передний план. Для пикера это не косметика: опрос `ccfzf --state`
//! идёт раз в секунду, пока окно показано, так что окно ssh выскакивало на
//! каждый опрос, уводило фокус, а `hideOnBlur` честно гасил пикер. Открыть
//! список было нельзя.
//!
//! `CREATE_NO_WINDOW` консоль всё равно выделяет (потомок `conhost.exe`
//! остаётся и с флагом — это не признак поломки), но окна ей не даёт. Та же
//! мера у соседа: `windowsHide: true` в его Node-модулях, и в
//! Node это ровно этот флаг.
//!
//! На macOS у процессов нет ни консолей, ни этой беды — там функция просто
//! отдаёт обычный `Command`.

use std::process::Command;

/// Флаг WinAPI: консольная программа запускается без окна консоли.
#[cfg(target_os = "windows")]
const CREATE_NO_WINDOW: u32 = 0x0800_0000;

/// `Command` для утилиты, которой окно не положено.
///
/// Через неё обязаны идти **все** вспомогательные консольные программы: `ssh`
/// за списком, `clip` за буфером обмена. Единственное исключение —
/// `spawn_detached` в `main.rs`: он поднимает терминал, окно которого и есть
/// цель, и флаг там был бы прямо вреден.
pub fn hidden_command(program: &str) -> Command {
    #[allow(unused_mut)]
    let mut cmd = Command::new(program);
    #[cfg(target_os = "windows")]
    {
        use std::os::windows::process::CommandExt;
        cmd.creation_flags(CREATE_NO_WINDOW);
    }
    cmd
}
