// Loaded twice: as a <script> in sessions.html and as a module in the tests.
// The project has no bundler, and duplicating this logic to make it testable
// would be worse than this shim.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SessionGlyph = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  // Признак «сессия живёт в приложении» — общий с фильтром `only windowed`
  // (см. докблок `inDesktopApp`). Загрузка это выдерживает: session-list.js
  // стоит раньше и в sessions.html, и в prepare-frontend.js.
  const listApi = typeof module === 'object' && module.exports
    ? require('./session-list')
    : globalThis.SessionList;

  // Состояние агента приходит в поле `agent` ответа `ccfzf --state`: агрегатор
  // читает его из <id>.state.json, куда пишет хук на стороне сессии. Ключи
  // здесь — ровно те строки, что пишет хук.
  const AGENT_DOT = {
    active: 'active',      // зелёный: агент работает
    question: 'question',  // жёлтый: агент о чём-то спрашивает
    review: 'review',      // оранжевый: закончил, результат ещё не смотрели
    idle: 'idle',          // серый: постоял законченным, считается проверенным
  };

  /**
   * Кружок состояния сессии.
   *
   * У закрытой сессии кружка нет — но место под него остаётся: строки стоят в
   * одной колонке, и убрать элемент целиком значило бы сдвинуть текст закрытых
   * строк относительно живых.
   *
   * Открытая сессия без состояния — не ошибка, а «хук не установлен или ещё не
   * сработал»; такой кружок серый, как у простаивающей. Красить её зелёным, как
   * раньше красили любую живую, теперь нельзя: зелёный стал означать «агент
   * прямо сейчас работает», и врать им не стоит.
   */
  function dotState(session) {
    // «Работа встала, посмотри» приходит двумя путями: stop и fail пишут
    // review сразу, а «Claude is waiting for your input» — через минуту после
    // остановки, и хук записывает его как idle, потому что описывает событие,
    // а не его смысл. Смысл у них один, и цвет должен быть один.
    //
    // Гаснет оно по открытию, а не по времени: agentSeen означает, что сессию
    // открывали уже после этой записи (отметку ставит сам пикер, см. поле
    // `seen` в buildSessionList). Ожидание от списка именно такое — сходил и
    // посмотрел, значит больше не висит.
    // Вопрос гаснет по тому же правилу. Агент при этом остаётся заблокированным,
    // и это осознанный размен: список, который продолжает звать после того, как
    // на сессию уже сходили, быстро перестаёт что-либо значить.
    const needsAttention = session.agentState === 'question'
      || session.agentState === 'review'
      || (session.agentState === 'idle' && session.agentEvent === 'attention');
    if (needsAttention) {
      if (session.agentSeen) return 'idle';
      return session.agentState === 'question' ? 'question' : 'review';
    }
    return AGENT_DOT[session.agentState] || 'idle';
  }

  function statusDotHtml(session) {
    if (!session || !session.live) return '<div class="dot closed"></div>';
    return `<div class="dot ${dotState(session)}"></div>`;
  }

  /**
   * Возраст последней активности: 31s, 5m, 1h 5m, 3d.
   *
   * `timestamp` — epoch-секунды, как их отдаёт claude-wt: и слоты, и хуки
   * пишут время в секундах. `nowSec` передаётся снаружи, чтобы функция
   * осталась чистой и проверяемой.
   *
   * Первая минута — в секундах, а не словом `now`. Слово отвечало «недавно» на
   * вопрос «сколько», и у работающей сессии, где колонка показывает длину
   * текущего хода, оно съедало ровно ту минуту, за которую по строке и видно,
   * началась работа только что или уже идёт.
   *
   * Часы идут вместе с минутами по той же причине, только на другом конце
   * шкалы: голый `1h` одинаково отвечал и про 1h01m, и про 1h59m, а ход
   * длиной в час у цикла `/do` и у ветки субагентов — обычное дело. Минуты
   * при нуле опускаются: `1h 0m` — три знака про ничто, а колонка узкая.
   *
   * У суток такой пары нет намеренно: сутками меряется история, а к ней
   * приходят за «когда-то давно», не за длиной хода.
   */
  function formatAge(timestamp, nowSec) {
    if (!timestamp || !Number.isFinite(timestamp)) return '';
    const delta = Math.max(0, Math.floor(nowSec - timestamp));
    if (delta < 60) return `${delta}s`;
    if (delta < 3600) return `${Math.floor(delta / 60)}m`;
    if (delta < 86400) {
      const hours = Math.floor(delta / 3600);
      const minutes = Math.floor((delta % 3600) / 60);
      return minutes ? `${hours}h ${minutes}m` : `${hours}h`;
    }
    return `${Math.floor(delta / 86400)}d`;
  }

  /**
   * Текстовый статус рядом с возрастом.
   *
   * Состояние и событие показываются вместе, потому что по отдельности они
   * недоговаривают: `review` бывает и от `stop`, и от `fail`, а `attention`
   * приходит и на вопрос, и на простой. Пара читается однозначно.
   *
   * Событие опускается, когда совпадает с состоянием, — дублировать слово ради
   * симметрии незачем.
   */
  function stateText(session) {
    if (!session || !session.agentState) return '';
    // Закрытая сессия ничего не делает — кроме той, за которую работает фоновый
    // агент (`claude agents`): своего окна у него нет, и «окно закрыто» про него
    // ничего не сообщает. Строка при этом остаётся строкой родителя.
    if (!session.live && !session.agentBackground) return '';
    const { agentState, agentEvent } = session;
    const text = !agentEvent || agentEvent === agentState
      ? agentState
      : `${agentState} · ${agentEvent}`;
    return session.agentBackground ? `bg ${text}` : text;
  }

  /**
   * Короткий id — то, чем сессию называют снаружи: `claude --resume`, имя файла
   * транскрипта, строка в ответе `ccfzf --state`. Четырёх знаков хватает, чтобы
   * узнать строку, а колонка при этом не съедает место у сводки.
   *
   * У сессии, за которую работает фоновый агент, показывается его id: искать по
   * нему будут именно того, кто пишет, а не того, от кого он форкнут.
   */
  function shortSessionId(session) {
    return String(session?.agentSessionId || session?.id || '').slice(0, 4);
  }

  /**
   * Статус агента в правой колонке.
   *
   * Выключенный чекбокс убирает колонку целиком, а не рисует пустую. Пустой
   * элемент нужен там, где у соседних строк колонка есть: без него правые
   * колонки разъезжаются. Чекбокс же выключен сразу у всего списка — и
   * разъезжаться нечему.
   *
   * Раньше эта колонка с выключенным «show event» показывала id: место одно,
   * вопрос один — «что это за строка». Теперь у id свой чекбокс, а с ним и своё
   * место — строка имени, а не правая группа.
   */
  function stateHtml(session, showEvent = true) {
    if (!showEvent) return '';
    return `<div class="state">${escapeHtml(stateText(session))}</div>`;
  }

  /**
   * Короткий id — подписью в строке имени, прижатой вправо; чем он полезен, см.
   * shortSessionId.
   *
   * Раньше это была колонка в правой группе, и место там дорогое: id стоял в
   * ряду величин, отвечающих на вопрос «стоит ли сюда заходить», а сам отвечает
   * на другой — «та ли это строка». В строке имени он рядом с тем, что опознают,
   * и не отнимает ширины у сводки.
   *
   * Элемент строчный: соседи по строке имени — подписи (`wname`, `pr`), и блок
   * сломал бы им ряд.
   */
  function sessionIdHtml(session, showId = false) {
    if (!showId) return '';
    return `<span class="sid">${escapeHtml(shortSessionId(session))}</span>`;
  }

  /**
   * Пометка «у этой сессии уже открыто окно терминала».
   *
   * Данные приходят от оконного трекера (windows11-manager), и это единственное в строке,
   * чего не знает `ccfzf --state`: он видит живые процессы, а не окна. Без
   * пометки живая сессия и живая сессия с окном выглядят одинаково, и Enter на
   * второй заводит второй процесс на том же транскрипте.
   *
   * Номер рабочего стола идёт в подсказку, а не в строку: на плитке места нет,
   * а спрашивают его редко — обычно достаточно знать, что окно вообще есть.
   * Стол `null` (трекер его не знал) подсказку не портит: тогда её просто нет.
   *
   * Пустой элемент вместо пропуска — по той же причине, что у hotkeyHtml:
   * правые колонки стоят друг за другом, и дырка сдвинула бы соседние строки.
   */
  /**
   * Терминалы, которые пометка различает поимённо.
   *
   * Один общий знак ⌨ на все терминалы сразу не годится: на Windows рядом
   * живут Windows Terminal и WezTerm, и вопрос к пометке — не «терминал ли
   * это» (это и так видно по ▣), а «какой именно». Отсюда буква на терминал,
   * а не картинка: колонка `.win` шириной в один знак, и иконке приложения
   * там места нет — а брать её было бы неоткуда вдвойне, окно стоит на
   * соседней машине, и её exe у нас не спросить.
   *
   * Порядок значим: `windowsterminal` обязан проверяться раньше `terminal`,
   * иначе Windows Terminal читался бы маковским Terminal.app. Имя приезжает
   * от трекера: на Windows это basename exe (`WindowsTerminal.exe`,
   * `wezterm-gui.exe`), на маке — отображаемое имя приложения (`kitty`,
   * `iTerm2`). Регэкспы поэтому свободные, но не настолько, как прежний общий
   * `wt` — тот совпадал в любом слове с этими двумя буквами подряд.
   */
  const TERMINAL_GLYPHS = [
    // `z` у WezTerm, а `w` у Windows Terminal — выбор владельца, и он не
    // произвольный: первая буква достаётся тому, у кого имя с неё начинается,
    // а WezTerm узнаётся по своей второй, характерной.
    { re: /wezterm/i, glyph: 'z', name: 'WezTerm' },
    { re: /kitty/i, glyph: 'k', name: 'kitty' },
    { re: /ghostty/i, glyph: 'g', name: 'Ghostty' },
    { re: /iterm/i, glyph: 'i', name: 'iTerm2' },
    { re: /windowsterminal|(^|[\\/])wt(\.exe)?$/i, glyph: 'w', name: 'Windows Terminal' },
    { re: /alacritty/i, glyph: 'a', name: 'Alacritty' },
    { re: /^terminal(\.app)?$/i, glyph: 'T', name: 'Terminal' },
  ];

  /**
   * Терминал записи окна, если трекер его назвал и он знаком.
   *
   * `null` значит «оставить ▣»: и когда поля нет вовсе (старый трекер), и
   * когда названо незнакомое приложение. Подставлять вместо этого пресет
   * терминала самого пикера было бы неправдой — у соседних строк терминалы
   * бывают разные, а окно вообще может стоять на чужой машине.
   */
  function terminalOf(win) {
    const named = String(win?.app || win?.process || '');
    if (!named) return null;
    return TERMINAL_GLYPHS.find(t => t.re.test(named)) || null;
  }

  /**
   * Пометка об открытом окне — по глифу на каждое окно.
   *
   * Окон у сессии бывает несколько: её открывают на двух машинах сразу.
   * Глиф на окно отвечает сразу на два вопроса — сколько их и в каком
   * терминале каждое, — а имена машин стоят соседней колонкой
   * (windowHostHtml).
   *
   * Запасная ветвь — `session.window` без `session.windows` — держит старый
   * агрегатор живым: он про несколько окон одной сессии не знает вовсе и
   * присылает одно.
   *
   * Подсказка складывается из того, что известно: стол называет трекер
   * Windows, имя терминала — оба, машину — новый агрегатор. Пустых
   * разделителей не бывает — склеиваются только непустые части.
   */
  function windowHtml(session, showWindow = true, showTerminalIcon = false) {
    if (!showWindow) return '';
    const wins = Array.isArray(session?.windows) && session.windows.length
      ? session.windows
      : (session?.window ? [session.window] : []);
    // Глиф приложения — не запись окна, и приезжает он не от трекера, а из
    // транскрипта (`entrypoint`). Окна у такой сессии не бывает вовсе:
    // трекер привязывает окно к сессии по заголовку, а заголовок окна
    // Claude Desktop — просто «Claude», и совпасть ему не с чем. Значит `c`
    // здесь единственный знак того, что строка живёт в приложении, — и он же
    // объясняет, почему Enter на ней ведёт себя иначе.
    //
    // Глифы окон он не отменяет, а встаёт перед ними: сессию приложения
    // продолжают и в терминале, и тогда она есть в обоих местах сразу.
    // Слушается той же галки, что и имена терминалов: вопрос у обоих один —
    // «чем эта сессия открыта».
    const app = showTerminalIcon && listApi.inDesktopApp(session)
      ? '<div class="win open" title="Claude Desktop">c</div>'
      : '';
    if (!wins.length) return app || '<div class="win"></div>';
    return app + wins.map((win) => {
      const terminal = showTerminalIcon ? terminalOf(win) : null;
      const parts = [];
      if (Number.isFinite(win.desktop)) parts.push(`Desktop ${win.desktop}`);
      if (terminal) parts.push(terminal.name);
      if (win.host) parts.push(String(win.host));
      const title = parts.length ? ` title="${escapeHtml(parts.join(' · '))}"` : '';
      return `<div class="win open"${title}>${terminal ? terminal.glyph : '▣'}</div>`;
    }).join('');
  }

  /**
   * Машина, на которой стоит окно этой сессии.
   *
   * Пометка ▣ одинакова у своего окна и у окна соседней машины, и по строке
   * было не понять, где оно стоит и почему Enter ведёт себя иначе: своё окно
   * поднимается, чужое — нет.
   *
   * Решение «чужая ли машина» принято раньше, при сборке строки: сюда приезжает
   * либо имя (или несколько через ', '), которое стоит назвать, либо пустая
   * строка. Пустой элемент вместо пропуска — по той же причине, что у `win` и
   * `hk`: правые колонки стоят друг за другом, и дырка сдвинула бы соседние
   * строки.
   *
   * Имя уже склеено строкой в session-list.js — здесь меняется только подпись
   * подсказки: одна машина или несколько.
   *
   * `windowHost` без `window` — не повод рисовать значок. С двумя
   * настроенными источниками `windowHost` ставится и без записи окна вовсе —
   * просто по имени источника строки (`ambiguous` в session-list.js): подпись
   * «Window is on <host>» тогда была бы неправдой — окна там нет, а с
   * `sshHost: user@remote-host` в неё вдобавок лезла бы ssh-строка, а не имя
   * машины. Про машину без окна уже сказано заголовком блока — вторая
   * подпись здесь только повторила бы враньё.
   */
  function windowHostHtml(session, showWindowHost = true) {
    if (!showWindowHost) return '';
    const host = session?.windowHost;
    const hasWindow = Boolean(session?.window) || (Array.isArray(session?.windows) && session.windows.length > 0);
    if (!host || !hasWindow) return '<div class="winhost"></div>';
    // Машин бывает две: сессию открывают и на соседней машине тоже.
    const label = host.includes(',') ? 'Windows are on' : 'Window is on';
    return `<div class="winhost" title="${label} ${escapeHtml(host)}">${escapeHtml(host)}</div>`;
  }

  /**
   * Имя сессии для заголовка диалога.
   *
   * Меню действий приходит с одним `label` и без заголовка окна, список — с
   * обоими; безымянная сессия остаётся с id, потому что пустой заголовок не
   * сообщает ничего.
   */
  function sessionName(session) {
    return session?.title || session?.label || String(session?.id ?? '');
  }

  /**
   * Хоткей проекта (`^F12`) — подписью в строке имени.
   *
   * Колонкой он был между двумя правками и колонкой быть перестал. Правая
   * группа отвечает на вопрос «стоит ли сюда заходить» — счёт задач, число
   * сессий, возраст, — а хоткей отвечает на другой, «чем эту строку открыть»,
   * и спрашивают его глазами там же, где читают имя. Тот же довод и то же
   * место, что у короткого id сессии; природа та же, что у метки PR и имени
   * окна, — подсказка рядом, а не колонка.
   *
   * Заодно это освободило место справа: колонка стояла между `count` и `age`
   * и раздвигала их у всех строк подряд, хотя клавиша есть у четырёх проектов
   * из сорока пяти.
   *
   * Пустой строки больше не остаётся вовсе: подписи в строке имени
   * схлопываются без следа, а сдвигать соседей ей нечего — колонок рядом нет.
   * У сессии функция не зовётся: `hotkey` ей не ставит никто (хоткей — признак
   * каталога, а не разговора), и колонка из пустых `div` висела бы у каждой
   * строки списка.
   */
  function hotkeyHtml(project, showHotkey = true) {
    const key = project?.hotkey ?? '';
    if (!showHotkey || !key) return '';
    // Занятую комбинацию гасим, а не прячем: человеку нужно видеть, какая
    // именно клавиша не сработала, а не только то, что что-то не сработало.
    const taken = project?.hotkeyTaken ? ' taken' : '';
    return `<span class="hk${taken}">${escapeHtml(key)}</span>`;
  }

  // Пороги подсветки контекста. До тридцати процентов заполненность ничего не
  // значит — она такая у любой сессии после пары ходов, и красить её значило бы
  // красить весь список. Дальше это уже предупреждение: за сорока процентами
  // начинают выпадать ранние куски разговора, и лучше узнать об этом из списка,
  // чем из ответа, который забыл, о чём шла речь.
  const CONTEXT_WARN = 30;
  const CONTEXT_HOT = 40;

  function contextLevel(pct) {
    if (pct >= CONTEXT_HOT) return 'hot';
    if (pct >= CONTEXT_WARN) return 'warn';
    return '';
  }

  /**
   * Деньги и контекст: «$2 13%».
   *
   * Сначала стоимость, потом контекст — тот же порядок, что и в карточке
   * сессии (session-info.js): две колонки об одном и том же, и разный порядок
   * заставлял бы перечитывать. Подсвечены только проценты: по ним решают, не
   * пора ли начинать заново, а стоимость — справка.
   *
   * Ноль показывается как ноль. Раньше он значил «данных нет» — перехват
   * статуслайна стоит не у каждой сессии (см. claude-wt-statusline.sh), — и
   * такая часть просто не рисовалась. На глаз это читалось не как «неизвестно»,
   * а как поломка отрисовки: у соседних строк цифры есть, у этой пусто.
   * Различать два случая всё равно нечем, и «0%» честнее пустоты.
   */
  function usageHtml(session, { showCost = true, showContext = true } = {}) {
    // Обе величины выключены — колонки нет вовсе; см. stateHtml о том, почему
    // выключенный чекбокс не оставляет за собой пустой элемент.
    if (!showCost && !showContext) return '';
    const pct = Number.isFinite(session?.agentContextPct) ? session.agentContextPct : 0;
    const cost = Number.isFinite(session?.agentCostUsd) ? session.agentCostUsd : 0;
    const parts = [];
    const level = contextLevel(pct);
    // Доли контекста бывает и не вовсе — у сессии приложения и у строки с
    // машины без хуков. Правило про это одно на строку и карточку и живёт в
    // session-list.js: два места об одном факте разошлись бы молча.
    const knowsContext = showContext && listApi.knowsContext(session);
    if (showCost) parts.push(`<span class="cost">$${cost}</span>`);
    if (knowsContext) parts.push(`<span class="ctx${level ? ` ${level}` : ''}">${pct}%</span>`);
    // Разделитель тот же, что у stateText: это две независимые величины, а не
    // одно число из двух частей, и пробела для такого мало.
    //
    // Пустой элемент вместо пропуска — по той же причине, что и у возраста:
    // колонки справа стоят друг за другом и не должны разъезжаться.
    return `<div class="usage">${parts.join(' · ')}</div>`;
  }

  /**
   * Комментарий человека к сессии — своей строкой под ответом.
   *
   * Три-четыре слова о том, что здесь делается. Отличается от всего
   * остального в строке тем, что это единственное, чего не сказал ни агент, ни
   * трекер: человек пишет его сам, и живёт он общим списком на машине
   * агрегатора — её `--state` читают пикеры всех машин.
   *
   * Пустой строки при пустом комментарии не остаётся: она заняла бы высоту у
   * каждой сессии без него, а таких почти все. То же правило, что у `prompt` и
   * `answer` рядом.
   */
  function commentHtml(session, show = true) {
    const text = (session || {}).comment;
    if (!show || typeof text !== 'string' || !text) return '';
    return `<div class="comment">${escapeHtml(text)}</div>`;
  }

  /**
   * Размер сессии — сколько раз человек в ней писал.
   *
   * Своя колонка, а не третья величина внутри `usage`: та отвечает на вопрос
   * «во что обошлось и сколько осталось до сжатия», а эта — «насколько
   * длинный тут разговор». Считает число агрегатор (`count_prompts` в ccfzf),
   * досчитывая, а не пересчитывая.
   *
   * Ноль печатается нулём. Сессия, в которой человек ещё ничего не написал,
   * бывает — её только что завели, — и пустота на её месте читалась бы как
   * «данных нет», а различать эти два случая нечем. То же решение и та же
   * причина, что у нулевой цены в usageHtml.
   *
   * Выключенная галка не оставляет пустого элемента: правые колонки стоят
   * друг за другом, и пустой div сдвигал бы соседей.
   *
   * Знак — речевой пузырь, а не карандаш. Карандашом (`✎`) подписан
   * комментарий человека, и один знак на два разных факта — «оставил заметку»
   * и «сколько раз писал агенту» — не различал ничего; счёт сообщений это
   * реплики, а не правка. Вариационный селектор U+FE0E просит текстовое
   * начертание: на Windows знак приезжает монохромным из Segoe UI Symbol, к
   * соседям по колонке (`▣ ⌂ ⌨ ☑`), а без просьбы система тянула бы цветной
   * эмодзи. Просьба и есть просьба: в BMP пузыря нет вовсе, и там, где
   * монохромного начертания у шрифта нет, знак останется цветным — проверять
   * глазами на каждой машине, как и `TERMINAL_GLYPHS`.
   */
  function promptsHtml(session, show = true) {
    if (!show) return '';
    const n = Number.isFinite((session || {}).promptCount) ? session.promptCount : 0;
    return `<div class="prompts">🗨︎${n}</div>`;
  }

  /**
   * Значок «у сессии есть спека или план».
   *
   * Пути приезжают полями `spec` и `plan` от агрегатора — он находит их в
   * хвосте транскрипта, потому что хука для этого нет (см. DOC_RE в ccfzf).
   *
   * Знак один на обе бумаги, и это решение: у сессии, дошедшей до плана,
   * почти всегда есть и спека, и два одинаковых значка рядом отвечали бы на
   * один вопрос дважды. Какая именно бумага за ним стоит, говорит подсказка,
   * и план в ней главнее спеки: спека отвечает «что решили», план — «где
   * сейчас», а из списка приходят за вторым.
   *
   * Пустого элемента при пустых полях не остаётся: бумаг нет у трёх сессий из
   * четырёх (22 из 100 на живой машине несут их), и пустой значок стоял бы
   * почти в каждой строке. То же правило и та же причина, что у prBadgeHtml.
   */
  function docsBadgeHtml(session) {
    const kind = docKindOf(session);
    return kind ? `<span class="docs" title="${kind}">▤</span>` : '';
  }

  /** Какая бумага представляет строку: план, спека или никакая. */
  function docKindOf(session) {
    const has = (name) => typeof (session || {})[name] === 'string' && session[name];
    if (has('plan')) return 'plan';
    if (has('spec')) return 'spec';
    return '';
  }

  /**
   * Счётчики списка задач у строки — и проекта, и сессии.
   *
   * Одна функция на оба вида строк намеренно: файл у них один и тот же (у
   * сессии — список задач её каталога), и второй рисовальщик того же числа
   * разошёлся бы с первым. Сессиям колонка досталась не сразу, и это была
   * ошибка: человек читает список сессий, а не проектов, и счёт нужен ему
   * там, где он работает.
   *
   * Поле `todo` приезжает от агрегатора списком секций по заголовкам первого
   * уровня — данными, а не готовой строкой: то же правило, по которому он не
   * отдаёт и `age`, а вторая форма на его стороне разошлась бы с колонкой.
   *
   * В строке — ведущая секция, как её рисует statusline-block.sh, и остаток
   * одним числом открытых. Полная разбивка уезжает в подсказку (rowTitle):
   * ширины на неё в колонке нет — у самого длинного из двадцати трёх проектов
   * с TODO на живой машине это «☑ 0/4 next │ 4 future │ 8 minor».
   *
   * Пустого элемента при пустом счёте не остаётся, и это не мелочь: файла нет
   * у двадцати проектов из сорока пяти, и пустая колонка стояла бы у половины
   * списка. Та же развилка и по той же причине — у usageHtml с обеими
   * выключенными галками.
   *
   * Числам из ответа функция не верит: поле собрано из файла на чужой машине,
   * и `NaN` в колонке читался бы поломкой пикера, а не испорченным входом.
   */
  function todoHtml(row, show = true) {
    const parts = todoParts(row);
    if (!show || !parts) return '';
    const tail = parts.tail ? ` <span class="rest">${escapeHtml(parts.tail)}</span>` : '';
    return `<div class="todo">${escapeHtml(parts.head)}${tail}</div>`;
  }

  /**
   * Счёт задач двумя кусками: ведущая секция и хвост «+N».
   *
   * Две части, а не готовая строка, ровно потому, что хвост тусклее ведущего
   * счёта и живёт в своём `span`. Читателя у этой функции два — разметка
   * (todoHtml) и мерка ширины колонки (todoText → projectColumnWidths), — и
   * вторая формула счёта разошлась бы с первой молча: колонка стала бы уже
   * своего содержимого, а виден был бы только обрезанный хвост.
   */
  function todoParts(row) {
    const sections = todoSections(row);
    if (!sections.length) return null;
    const lead = sections[0];
    const total = lead.done + lead.todo;
    // Хвост — сумма открытых, а не всех: сделанное в дальних секциях на
    // вопрос «сколько ещё осталось» не отвечает.
    const rest = sections.slice(1).reduce((n, sec) => n + sec.todo, 0);
    const label = lead.label ? ` ${lead.label}` : '';
    return { head: `☑ ${lead.done}/${total}${label}`, tail: rest ? `+${rest}` : '' };
  }

  /** Тот же счёт голым текстом — им меряется ширина колонки. */
  function todoText(row) {
    const parts = todoParts(row);
    if (!parts) return '';
    return parts.tail ? `${parts.head} ${parts.tail}` : parts.head;
  }

  /** Секции счётчика, приведённые к числам. Не список — пустота. */
  function todoSections(row) {
    const raw = row && row.todo;
    if (!Array.isArray(raw)) return [];
    // Имя переменной не `s` намеренно: сторож контракта строки
    // (row-contract.test.js) считает всякое `s.<имя>` обращением к полю
    // сессии, и секция под этим именем записала бы `done` и `todo` в её
    // контракт — поля, которых у сессии нет и быть не должно.
    return raw
      .filter(sec => sec && typeof sec === 'object')
      .map(sec => ({
        label: typeof sec.label === 'string' ? sec.label : '',
        done: Number.isFinite(sec.done) ? sec.done : 0,
        todo: Number.isFinite(sec.todo) ? sec.todo : 0,
      }));
  }

  /**
   * Сколько у проекта сессий и сколько из них живых: «17 · 1●».
   *
   * Разметка и текст рядом, по той же причине, что у todoParts: ширину
   * колонки меряют этим же текстом, и вторая его формула разошлась бы с
   * колонкой молча.
   */
  function projectCountHtml(project) {
    return `<div class="count">${escapeHtml(projectCountText(project))}</div>`;
  }

  function projectCountText(project) {
    const total = Number.isFinite(project?.sessionCount) ? project.sessionCount : 0;
    const live = Number.isFinite(project?.liveCount) ? project.liveCount : 0;
    return live ? `${total} · ${live}●` : `${total}`;
  }

  // Мерка ширины: сколько знаков «0» занимает строка. Цифры под
  // `font-variant-numeric: tabular-nums` равны «0» ровно, буквы уже — оценка
  // выходит с запасом, и это верная сторона ошибки: колонка чуть шире
  // содержимого никому не мешает, уже — режет счёт. Знаки вне ASCII (☑, ●, ·)
  // считаются в полтора: метрики у них самые непредсказуемые, а на WebView2
  // тем более.
  function textCells(text) {
    let cells = 0;
    for (const ch of String(text ?? '')) cells += ch.charCodeAt(0) > 127 ? 1.5 : 1;
    return cells;
  }

  /**
   * Ширины правых колонок строки проекта — в знаках «0» (`ch`).
   *
   * Правая группа прижата вправо, поэтому левый край каждой колонки задаётся
   * шириной всех колонок правее неё: пока ширина считается по содержимому,
   * «172 · 4●» у одного проекта сдвигает счёт задач у него же, и левые края
   * `todo` стоят лесенкой. Общая ширина на все строки и есть табличная
   * раскладка.
   *
   * Считается по видимым строкам, а не по всему ответу агрегатора: колонка
   * должна быть не шире, чем нужно тому, что на экране. И считается здесь, а
   * не замером DOM: замер живёт только в браузере, а это правило — обычная
   * функция, и сторож у неё обычный.
   */
  function projectColumnWidths(projects, nowSec) {
    const rows = Array.isArray(projects) ? projects : [];
    const widest = (textOf) => rows.reduce((max, row) => Math.max(max, textCells(textOf(row))), 0);
    return {
      todo: widest(todoText),
      count: widest(projectCountText),
      age: widest((row) => ageText(row, nowSec)),
    };
  }

  /**
   * Возраст в строке. У работающей сессии — время текущего хода.
   *
   * Колонка отвечает на вопрос «сколько уже», и у работающей сессии прежний
   * ответ был бесполезен: `lastActivity` двигает каждый вызов инструмента, а их
   * десятки в минуту, — там вечно стояло `now`. Спрашивают же про другое:
   * сколько крутится текущая команда. Возраст всей сессии для этого тоже не
   * годится, он про «46m» независимо от того, работает она или спит час.
   *
   * Метка есть только у сессий, поднятых после правки в хуке; без неё колонка
   * остаётся прежней. Пустой элемент вместо пропуска: колонки справа стоят
   * друг за другом и не должны разъезжаться.
   */
  function ageHtml(session, nowSec) {
    return `<div class="age">${ageText(session, nowSec)}</div>`;
  }

  /** Тот же возраст голым текстом: им меряется ширина колонки у проектов. */
  function ageText(session, nowSec) {
    const working = Boolean(session) && session.agentState === 'active';
    const turnAt = working && Number.isFinite(session.agentTurnAt) ? session.agentTurnAt : 0;
    return formatAge(turnAt || (session && session.lastActivity), nowSec);
  }

  // Домашний каталог агента в пути ничего не сообщает: он одинаков у всех
  // сессий и занимает треть строки. Имя пользователя не зашито — агенты живут
  // и на других машинах.
  const HOME_PREFIX = /^\/home\/[^/]+/;

  // Уведомление о простое. Приходит тем же событием attention, что и просьба о
  // разрешении, и именно поэтому раньше попадало в подсказку — по нему одному
  // и различались жёлтый кружок с серым. Но различает их теперь сам статус, а в
  // подсказке эта строка висит на каждой отдохнувшей сессии и вытесняет то,
  // ради чего в подсказку и смотрят.
  const IDLE_NOTICE = 'waiting for your input';

  /** Путь агента без домашнего каталога. */
  function shortPath(cwd) {
    return String(cwd ?? '').replace(HOME_PREFIX, '~');
  }

  /**
   * Слова текста для сравнения «это то же имя, просто по-другому набрано».
   *
   * Разделитель — всё, что не буква и не цифра: `ccfzf_picker` и
   * `ccfzf-picker` для человека одно и то же имя, разбитое на слова разным
   * знаком, а для строкового сравнения — два разных значения.
   */
  function wordSet(text) {
    return new Set(
      String(text ?? '')
        .split(/[^a-zA-Z0-9]+/)
        .map((word) => word.toLowerCase())
        .filter(Boolean),
    );
  }

  /** Последний непустой сегмент пути — basename и по `/`, и по `\`. */
  function pathBasename(cwd) {
    const parts = String(cwd ?? '').split(/[/\\]+/).filter(Boolean);
    return parts.length ? parts[parts.length - 1] : '';
  }

  // Параметры не названы `a`/`b`: тест «поле действительно есть в строке»
  // (row-contract.test.js) вычитывает из этого файла все `session.`/`s.`/
  // `a.`/`b.` обращения как имена полей сессии — однобуквенные имена здесь
  // ловились бы той же регуляркой и приписали бы строке поле `has`, которого
  // у неё нет и не должно быть.
  function isSubset(small, big) {
    for (const item of small) if (!big.has(item)) return false;
    return true;
  }

  /**
   * Каталог уже назван именем строки — вторая подпись с тем же смыслом
   * только отнимает место.
   *
   * Сравниваются множества слов, а не строки целиком: разделители у людей
   * разные (`_` против `-`), а порядок слов и регистр значения не имеют.
   * Правило одностороннее — «одно множество внутри другого», а не равенство:
   * `picker` внутри `ccfzf-picker` тоже читается как то же имя в
   * сокращении, а точное совпадение такой случай упустило бы. Пустое имя или
   * пустой каталог гасить нечем — сравнивать не с чем.
   */
  function hidesProject(name, cwd) {
    const nameWords = wordSet(name);
    const dirWords = wordSet(pathBasename(cwd));
    if (!nameWords.size || !dirWords.size) return false;
    return isSubset(nameWords, dirWords) || isSubset(dirWords, nameWords);
  }

  /**
   * Вторая строка под именем в списке: каталог проекта — basename, а не
   * сокращённый путь. Полный путь остаётся в подсказке (rowTitle, через
   * shortPath); здесь короче не значит менее понятно, а вопрос один — «какой
   * это каталог», не «где он на диске».
   *
   * Пустая строка, когда имя уже сказало то же самое: см. hidesProject.
   */
  function projectLine(name, cwd) {
    return hidesProject(name, cwd) ? '' : pathBasename(cwd);
  }

  /**
   * Имя окна рядом с именем строки — и только когда они разошлись.
   *
   * Имён у сессии два, и приезжают они разными дорогами. `title` — заголовок
   * транскрипта (`custom-title`/`ai-title`), его пишет агент; `windowTitle` —
   * то, чем сессию назвал человек, заводя окно, и то, по чему её привязывает к
   * окну трекер. У долгой сессии первое остаётся от работы, ради которой её
   * когда-то завели, а второе называет сегодняшнюю: строка `esm-migration`
   * оказывалась единственным следом сессии, которую человек знает как
   * `tray-build-time`, — и найти её в списке было нечем.
   *
   * Мерка совпадения — та же, что у второй строки с каталогом (hidesProject):
   * множества слов, а не строки целиком. Разделители у людей разные, и
   * `ccfzf_picker` рядом с `ccfzf-picker` был бы подписью ни о чём.
   */
  function windowNameHtml(session) {
    const name = String(session?.windowTitle ?? '').trim();
    if (!name) return '';
    const own = wordSet(session?.title);
    const win = wordSet(name);
    if (own.size && win.size && (isSubset(own, win) || isSubset(win, own))) return '';
    return `<span class="wname">${escapeHtml(name)}</span>`;
  }

  /**
   * Подсказка при наведении на строку.
   *
   * Здесь оседает то, чему в строке не хватает места: полный путь (в строке он
   * обрезан многоточием), чем сессия закончила и текст уведомления агента.
   *
   * Пустая строка означает «подсказки нет» — вызывающий не добавляет атрибут,
   * иначе браузер показывал бы пустую рамку.
   */
  function rowTitle(session) {
    if (!session) return '';
    const lines = [];
    if (session.cwd) lines.push(shortPath(session.cwd));
    // Последний запрос человека — над сводкой ответа. В строке их нет (там
    // место только у пути), а в подсказке оба к месту: «что спросили» и
    // «чем ответили» читаются разными строками, а не одной кашей.
    if (session.agentPrompt) {
      if (lines.length) lines.push('');
      lines.push(session.agentPrompt);
    }
    // Первая строка последнего ответа агента. Отвечает на вопрос «чем эта
    // сессия закончила», на который ни кружок, ни заголовок окна не отвечают:
    // «Закоммитил — ea527f0, рабочее дерево чистое» против «Дизайн, секция 1
    // из 5».
    //
    // У работающей сессии свежей сводки нет — она отвечает за текущий ход, а он
    // ещё идёт. Тогда показывается последняя известная; склейку «сводка, а у
    // работающей — предыдущая» считает sessionDescription (session-agent.js) —
    // один раз на сборке строки, чтобы копии этого `||` не разъезжались.
    // Если промпт уже открыл блок — сводку не отбиваем пустой строкой снова.
    const summary = session.agentDescription ?? '';
    if (summary) {
      if (lines.length && !session.agentPrompt) lines.push('');
      lines.push(summary);
    }
    const message = session.agentMessage ?? '';
    if (message && !message.includes(IDLE_NOTICE)) lines.push(message);
    // Полная разбивка счётчика задач — ради неё колонка и показывает
    // только ведущую секцию. Вопрос «а в какой секции они лежат» задают
    // редко, и ответ на него ширины в строке не окупает.
    //
    // Каждая секция — сделано из всего в ней, а не число открытых: в колонке
    // хвост сложен в «сколько ещё», здесь же человек читает состав, и дробь
    // отвечает на «сколько из скольких» у каждой.
    const todo = todoSections(session)
      .map(sec => `${sec.label ? `${sec.label} ` : ''}${sec.done}/${sec.done + sec.todo}`)
      .join(' · ');
    if (todo) lines.push(todo);
    return lines.join('\n');
  }

  /** Готовый атрибут title, уже экранированный, либо пустая строка. */
  function titleAttr(session) {
    const text = rowTitle(session);
    return text ? ` title="${escapeHtml(text)}"` : '';
  }

  function escapeHtml(text) {
    return String(text).replace(/[&<>"]/g, (c) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
  }

  // Номер PR берётся из хвоста ссылки, отдельного поля для него нет: `pr_url`
  // пишет хук, и второе поле означало бы два источника правды об одном и том же.
  //
  // Форма сегмента owner/repo — только то, что GitHub туда и пускает: буквы,
  // цифры, точка, подчёркивание, дефис. `[^/]+` («что угодно, кроме слэша»)
  // пропускал бы и `&`, `|`, `"`, пробел, перевод строки внутри сегмента — а
  // ссылка уходит дальше в команду открытия браузера, где всё это опасно.
  // Отсюда же и требование https://github.com/: ссылку в строку пишет хук, а
  // не человек, и подписывать чем попало её открытие незачем.
  function prNumber(url) {
    const m = /^https:\/\/github\.com\/[A-Za-z0-9._-]+\/[A-Za-z0-9._-]+\/pull\/(\d+)$/.exec(url ?? '');
    return m ? m[1] : '';
  }

  /**
   * Метка PR в строке: «↗ #3».
   *
   * Текстом, а не картинкой: ассетов у пикера нет вовсе, а стрелка есть в Segoe
   * UI, которым он и набран.
   */
  function prBadgeHtml(session) {
    const num = prNumber(session?.pr_url);
    return num ? `<span class="pr">↗ #${num}</span>` : '';
  }

  return {
    statusDotHtml, formatAge, ageHtml, stateText, shortSessionId, stateHtml,
    sessionIdHtml, sessionName, hotkeyHtml, contextLevel, usageHtml, windowHtml, windowHostHtml,
    todoHtml, todoText, projectCountHtml, projectCountText, projectColumnWidths, ageText,
    TERMINAL_GLYPHS, terminalOf,
    shortPath, rowTitle, titleAttr, escapeHtml,
    prNumber, prBadgeHtml, wordSet, hidesProject, projectLine, windowNameHtml,
    docsBadgeHtml, docKindOf, promptsHtml, commentHtml,
  };
});
