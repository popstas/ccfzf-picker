// Loaded twice: as a <script> in sessions.html and as a module in the tests.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.ActionIcons = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  /**
   * Значки пунктов, у которых приложения нет.
   *
   * Два знака взяты из строки списка не для красоты: `▣` там помечает
   * открытое окно. `●` — не тот же знак, что в списке (там непросмотренная
   * сессия горит кружком `.dot.review`, крашенным CSS), а тот же цвет и та же
   * круглая форма: совпадение достаточное, чтобы знак читался как то же самое
   * дело.
   */
  const GLYPHS = {
    new: { text: '+' },
    // Приглашение шелла: пункт открывает терминал в том же каталоге, а `+`
    // рядом заводит в нём сессию агента. Пара читается формой — знак нового
    // отвечает «ещё одна», этот «сюда руками».
    terminal: { text: '❯' },
    info: { text: 'ⓘ' },
    unread: { text: '●', cls: 'unread' },
    // Пустой кружок против залитого у `unread`: пара читается формой, а не
    // цветом — цвет у «просмотрено» был бы нейтральным и пропал бы в меню.
    seen: { text: '○' },
    attach: { text: '⧉' },
    'open-remote': { text: '▣' },
    // Стрелка по кругу, а не `▣`: восстановление снимка — «вернуть как было»,
    // а не «открыть окно». Знак открытого окна занят соседним пунктом, и
    // повтори мы его здесь, два разных дела читались бы одинаково.
    restore: { text: '⟲' },
    // Раскладки рисуются собой: сетка из четвертей — плитка, две сдвинутые
    // рамки — каскад. Пара читается формой, как `unread`/`seen`: вопрос у
    // человека не «раскладка ли это», а «какая именно».
    tile: { text: '▦' },
    cascade: { text: '❐' },
  };

  /**
   * Октикон `mark-github`, 16×16, вшитый строкой.
   *
   * Картинка тут не от exe, а своя: у PR приложения нет вовсе — есть служба, и
   * узнают её по значку, а не по стрелке `↗`, которая стояла тут раньше и
   * значила «уедет наружу», а не «GitHub». Файлом рядом класть нельзя: статику
   * собирает `scripts/prepare-frontend.js` перечислением, и картинка приехала
   * бы в бинарь только вместе с правкой того списка. Цвет прибит гвоздями
   * (`fill`), а не взят из `currentColor`: внутрь `<img>` каскад страницы не
   * попадает.
   */
  const GITHUB_MARK = 'data:image/svg+xml;utf8,' + encodeURIComponent(
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16">'
    + '<path fill="#e6edf3" d="M8 0C3.58 0 0 3.58 0 8c0 3.54 2.29 6.53 5.47 7.59.4.07.55-.17.55-.38'
    + ' 0-.19-.01-.82-.01-1.49-2.01.37-2.53-.49-2.69-.94-.09-.23-.48-.94-.82-1.13-.28-.15-.68-.52-.01-.53'
    + '.63-.01 1.08.58 1.23.82.72 1.21 1.87.87 2.33.66.07-.52.28-.87.51-1.07-1.78-.2-3.64-.89-3.64-3.95'
    + ' 0-.87.31-1.59.82-2.15-.08-.2-.36-1.02.08-2.12 0 0 .67-.21 2.2.82.64-.18 1.32-.27 2-.27s1.36.09 2 .27'
    + 'c1.53-1.04 2.2-.82 2.2-.82.44 1.1.16 1.92.08 2.12.51.56.82 1.27.82 2.15 0 3.07-1.87 3.75-3.65 3.95'
    + '.29.25.54.73.54 1.48 0 1.07-.01 1.93-.01 2.2 0 .21.15.46.55.38A8.013 8.013 0 0 0 16 8c0-4.42-3.58-8-8-8Z"/>'
    + '</svg>',
  );

  /** Картинки, которые не нужно ни у кого спрашивать. */
  const IMAGES = {
    pr: GITHUB_MARK,
  };

  /** Настроенное действие, чей exe не нашёлся: нейтральное «запустить». */
  const FALLBACK = { text: '▸' };

  /**
   * Где искать агента ради значка пункта `new`.
   *
   * Кандидатов два, и второй не от жадности: своей строки в `PATH` у агента на
   * Windows может не быть вовсе — установщик кладёт его в каталог с версией
   * внутри имени. Версия меняется с каждым обновлением, поэтому в пути стоит
   * `*`: жёсткий путь протух бы молча, значок просто исчез бы. Разбирает `*`
   * Rust (`icons.rs`), он же берёт первого кандидата, который дал иконку.
   */
  const NEW_ICON_PATHS = ['claude.exe', '%APPDATA%\\Claude\\claude-code\\*\\claude.exe'];

  /**
   * Что спросить у Rust.
   *
   * Список собирает страница, а не Rust: тот умеет ровно «дай иконку этого
   * файла» и про меню не знает ничего. `icon` перевешивает `argv[0]` — он и
   * заведён ради случая, когда argv[0] не приложение (`cmd /c start` у
   * проводника). Пункт `new` в конфиге не описан, но иконку у него взять
   * есть откуда — у агента; нет агента на машине — встанет глиф.
   */
  function iconSpecs(config) {
    const specs = NEW_ICON_PATHS.map(path => ({ id: 'new', path }));
    for (const action of (config && config.actions) || []) {
      const path = action.icon || (action.argv || [])[0] || '';
      if (path) specs.push({ id: action.id, path });
    }
    return specs;
  }

  /**
   * Значок строки меню: картинка, если она есть, иначе глиф.
   *
   * Иконка приложения главнее вшитой картинки: `IMAGES` — про пункты, у
   * которых приложения нет, и настроенный exe на том же id значил бы, что
   * приложение всё-таки появилось.
   *
   * Возвращается описание, а не готовый HTML: экранирование живёт на
   * странице, вместе с остальной сборкой строки, — второй escapeHtml здесь
   * разошёлся бы с ним молча.
   */
  function actionIcon(action, icons) {
    const id = (action || {}).id;
    const src = (icons || {})[id] || IMAGES[id];
    if (src) return { kind: 'img', src };
    const glyph = GLYPHS[id] || FALLBACK;
    return { kind: 'glyph', text: glyph.text, cls: glyph.cls || '' };
  }

  return { GLYPHS, IMAGES, iconSpecs, actionIcon };
});
