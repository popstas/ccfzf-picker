(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SessionList = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  // globalThis, а не `root`: тот виден только внешней функции шима, а внутрь
  // factory не передаётся.
  const agentApi = typeof module === 'object' && module.exports
    ? require('./session-agent')
    : globalThis.SessionAgent;
  const windowApi = typeof module === 'object' && module.exports
    ? require('./session-windows')
    : globalThis.SessionWindows;

  /**
   * Строки списка из ответа агрегатора.
   *
   * Фоновый агент своей строки не получает: он форкнут от родителя и работает
   * вместо него. Его поля подставляются в строку родителя, а сам он из списка
   * исключается — иначе форк отобрал бы у родителя его же окно.
   *
   * Подставляются при этом не только поля агента: окно и живость — тоже.
   * Терминал у форка бывает: фоновое задание занимает собой то самое окно, из
   * которого его завели, и трекер привязывает окно к его id.
   *
   * Имена полей здесь — те же, что читают отрисовщики (session-glyph.js,
   * session-info.js, session-groups.js, picker-filter.js): всё, что пришло из
   * записи агента, носит префикс `agent`, а `pr_url` и `lastActivity` названы
   * так же, как у них. Один словарь на весь проект — иначе строка собирается
   * под одними именами, а рисуется по другим, и половина колонок молча пустеет.
   * Единственное поле, которое строка не отдаёт наружу, — `label`: его
   * приписывает labelSessions (session-groups.js) уже над готовым списком.
   */
  /**
   * Имя машины окна этой карточки, если оно чужое, и пустота, если своё.
   *
   * Своё имя тут шум: у большинства карточек окно там же, где пикер, и поле
   * из повторяющегося имени машины не сообщало бы ничего. Наружу — имя как
   * его написал трекер, а не приведённое к нижнему регистру: сравнивают
   * машины без учёта регистра (`windowApi.normHost`), а показывают как есть.
   *
   * Раньше это была функция `foreignHosts`, отдававшая список: одна строка
   * несла все окна сессии разом, и чужих машин у неё могло быть несколько.
   * Теперь окон в строке одно (карточка — по одной на окно), и вопрос всегда
   * «эта машина своя или чужая», а не «какие из них чужие».
   */
  function windowHostOf(win, configHost) {
    const raw = win && win.host;
    const host = windowApi.normHost(raw);
    if (!host) return '';
    const mine = windowApi.normHost(configHost);
    if (host === mine) return '';
    return String(raw).trim();
  }

  /**
   * Машина, названная источником строки.
   *
   * Ответ на вопрос «чья это сессия» у строки без окна: раньше его давало
   * отсутствие окна («нет окна — значит своя»), и при одном источнике это было
   * верно. С двумя источниками так соврёшь: удалённая сессия без окна встала бы
   * в блок местных. Зовётся только когда источников в ответе больше одного
   * (см. `ambiguous` в `buildSessionList`) — при одном сравнивать нечего, и
   * прежнее «нет окна — значит своя» остаётся верным.
   *
   * Отдаётся дословно, как записан `sshHost`: этой же строкой адресуются
   * действия, и «красивое» имя машины увело бы ssh не туда.
   */
  function sourceHostOf(source) {
    const label = String(source || '').trim();
    if (!label || label === 'local') return '';
    return label;
  }

  /**
   * Живёт ли сессия в приложении Claude Desktop.
   *
   * Общая на двоих: по ней рисуется глиф `c` в колонке окна
   * (`windowHtml` в session-glyph.js) и по ней же фильтр «only windowed»
   * считает такую строку оконной (`buildSessionsPayload` в
   * session-groups.js). Два правила про одно разошлись бы молча — и уже
   * разошлись: пометка окна в строке стояла, а отсев «покажи то, что сейчас
   * на экране» строку выбрасывал.
   *
   * Своей машины предикат не спрашивает, в отличие от `isDesktopRow`
   * (open-transport.js): та решает, куда вести Enter, и ссылка работает
   * только у себя, — а пометка честна и у чужой строки. Сессия в приложении
   * соседней машины на экране всё-таки открыта.
   */
  function inDesktopApp(row) {
    return (row || {}).entrypoint === 'claude-desktop';
  }

  /**
   * Знает ли строка свою долю контекста.
   *
   * Считает её перехват статуслайна (`claude-wt-statusline.sh`), а стоит он не
   * везде. У Claude Desktop статуслайна нет вовсе. На машине без хуков — ни на
   * Windows, ни на маке — его тоже нет, и состояние такой строке собирает сам
   * агрегатор из хвоста транскрипта; узнаётся такая запись по `source`. В
   * обоих случаях `contextPct` приходит нулём, и показанный ноль был бы
   * единственным числом строки, которое врёт.
   *
   * Оговорка к правилу «ноль честнее пустоты», а не отмена его: то правило
   * написано про случай, где «данных нет» и «правда ноль» неразличимы, —
   * здесь признак прямой.
   *
   * Общая на строку и карточку (`usageHtml` и `session-info.js`): два места об
   * одном факте разошлись бы молча. До появления второго случая правило и
   * стояло двумя выражениями — сойтись им помогало только то, что случай был
   * один.
   */
  function knowsContext(row) {
    return !inDesktopApp(row) && (row || {}).agentSource !== 'transcript';
  }

  function buildSessionList({ sessions, seen, state, configHost } = {}) {
    const list = Array.isArray(sessions) ? sessions : [];
    const byId = {};
    for (const s of list) if (s && s.id) byId[s.id] = s;
    const marks = seen || {};

    // Различать машины по источнику имеет смысл только тогда, когда в
    // ответе их несколько: с одним источником отличать нечего, все строки
    // приехали оттуда же, и старое умолчание («нет окна — значит своя»)
    // верно по-прежнему. Обычная установка (один `sshHost`, без
    // `localSource`) от этого правила не меняется ни на бит: сессии без
    // окна остаются в «Active sessions», как и всегда.
    const distinctSources = new Set(
      list.map(s => String((s || {}).source || '').trim()).filter(Boolean),
    );
    const ambiguous = distinctSources.size > 1;

    const rows = [];
    for (const s of list) {
      if (!s || !s.id || s.kind === 'background') continue;
      const active = agentApi.activeAgent(s, byId);
      const agent = active.agent;
      // Сессия, у которой спрашивают про окно и про живость, — та, что на
      // самом деле работает. Обычно это она сама; у фонового форка — он.
      const worker = active.background ? (byId[active.id] || s) : s;
      // Все окна сессии: её открывают и на двух машинах сразу. Список
      // приезжает готовым от агрегатора, порядок — «свежайший взгляд
      // первым», и здесь он не пересчитывается.
      //
      // Своих окон нет — берутся окна форка. Правило это продолжает то, по
      // которому форк не получает своей строки: раз его поля подставляются в
      // строку родителя, то и окно с живостью — тоже. Фоновое задание
      // занимает собой терминал, и трекер привязывает окно к **его** id (id
      // называют хуки, а пишет их с этого момента форк); родитель при этом
      // перестаёт быть живым — процесс ушёл. Без этой подстановки строка
      // уезжала в историю, форка в списке не было вовсе, и живое
      // отслеживаемое окно не показывал никто.
      //
      // Не складываются, а замещают: у обычного `claude agents` окно остаётся
      // за родителем, а одно и то же окно, привязанное разными трекерами к
      // разным id, дало бы на одной машине две карточки.
      const own = windowApi.windowsOf(s, state);
      const sessionWindows = own.length ? own : windowApi.windowsOf(worker, state);
      // Живость складывается, а не подменяется: форк кончился, а родитель
      // работает — строка обязана остаться живой.
      const live = Boolean(s.live) || (active.background && Boolean(worker.live));
      const mark = marks[s.id] || 0;

      // Сессия с N окнами даёт N карточек — по одной на окно, — а сессия без
      // окон одну, как и раньше. Общие для сессии поля (работа агента,
      // стоимость, контекст) при этом повторяются на каждой карточке: агент
      // один, и ждёт он человека через любое из окон.
      const perCard = sessionWindows.length ? sessionWindows : [null];
      for (const w of perCard) {
        // Отметок о просмотре две, и обе настоящие. Своя — от открытия сессии
        // из списка; она единственная там, где оконного трекера нет вовсе (на
        // маке). Чужая приезжает от трекера **этого** окна: он видит переход
        // взгляда именно на него, а пикер об этом не узнаёт ниоткуда.
        //
        // Побеждает поздняя: «посмотрел» верно с той секунды, когда
        // посмотрели, чем бы это ни было. Обратный ход — «Mark unread» —
        // поэтому и не может быть только местным: отмотанную здесь отметку
        // трекерная перебила бы на следующем же опросе, и её отматывают у
        // трекера, причём у **всех** окон сессии разом (см. unreadBases в
        // session-windows.js и markUnread в sessions.html) — иначе сосед,
        // которого не тронули, вернул бы «просмотрено» на первой же карточке.
        const focusedAt = Math.max(mark, (w || {}).focusedAt || 0, 0);
        rows.push({
          id: s.id,
          title: s.title || '',
          cwd: s.cwd || '',
          live,
          frozen: Boolean(s.frozen),
          pid: s.pid || 0,
          tty: s.tty || '',
          tmux: s.tmux || null,
          // Зелийная сессия, в которой живёт процесс. Того же рода, что и
          // `tmux`, и читает её то же место (chooseOpenStrategy): отсоединённая
          // зелийная сессия — единственный случай, когда терминал сессии
          // существует, но не открыт нигде, и без этого поля найти его нечем.
          zellij: s.zellij || null,
          kind: s.kind || 'interactive',
          // Клиент, которым сессию открывали в последний раз: `cli` у
          // терминального, `claude-desktop` у приложения. Приезжает полем
          // ответа агрегатора, а тот берёт его из транскрипта — больше этой
          // разницы не видно нигде: файл, каталог и формат у обеих сессий
          // одинаковые.
          //
          // Читателей двое: Enter (`chooseEnterAction` — сессию приложения он
          // возвращает в приложение) и глиф `c` в колонке окна. Пустая строка,
          // а не отсутствие поля: у прежнего агрегатора поля нет вовсе, и
          // `undefined` уехал бы в стог поиска словом — то же правило, что у
          // `windowTitle` ниже.
          entrypoint: String(s.entrypoint || ''),
          mtime: s.mtime || 0,
          gist: s.gist || '',
          // Своё окно этой карточки — то же самое, что и единственный элемент
          // `windows` ниже. `null`, а не отсутствие поля: у отрисовщика не
          // должно быть третьего случая «поля нет вовсе». «Окна нет» и «про
          // окна ничего не известно» сознательно неразличимы — разница видна
          // только в конфиге, а по строке списка её не показать.
          window: w,
          // Своё окно карточки, одним элементом. Отсюда получится и один
          // глиф на карточке, и верный Enter: `focusWindowOf` ходит через
          // `windowsOf`, а та читает именно это поле.
          windows: w ? [w] : [],
          source: String(s.source || ''),
          // Запись окна ответ на вопрос: окно называет машину, на экране которой
          // сессия видна, и этот ответ полный — включая когда ответ «своя машина».
          // Источник спрашивается только если записи окна нет вовсе.
          windowHost: w ? windowHostOf(w, configHost) : (ambiguous ? sourceHostOf(s.source) : ''),
          // Заголовок своего окна — то самое имя, которым сессию завёл человек
          // (`claude -n tray-build-time`): по нему её и опознают. `title`
          // строки приезжает из транскрипта (custom-title/ai-title) и с ним
          // расходится — у долгой сессии он остаётся от той работы, ради
          // которой её когда-то завели. Поле отдельное, потому что читателей у
          // него двое: поиск (picker-filter.js) и подпись рядом с именем
          // (windowNameHtml). Пустая строка, а не отсутствие поля: стог поиска
          // склеивается из полей, и недостающее уехало бы туда словом
          // `undefined`.
          windowTitle: (w || {}).title || '',
          // Все окна сессии целиком, без урезания до «своего». Единственный
          // потребитель — unreadBases (session-windows.js): отмотка
          // «просмотрено» обязана уйти каждому трекеру сессии, а не только
          // трекеру окна этой карточки, — поэтому поле отдельное от `windows`,
          // а не общее с ним.
          sessionWindows,
          branch: (agent || {}).branch || '',
          pr_url: (agent || {}).pr_url || '',
          // Спека и план — поля самой сессии, а не записи агента: их находит
          // агрегатор в хвосте транскрипта, а не хук. Префикса `agent` у них
          // поэтому нет.
          //
          // Пути относительные, внутри `cwd`: файл лежит на машине
          // агрегатора, а открывает его пикер у себя, переведя каталог через
          // свой pathMap. Пустая строка, а не undefined, — то же правило, что
          // у `pr_url` рядом.
          // Счётчики списка задач каталога сессии — те же, что у строки её
          // проекта: файл один на обе строки. Пустой список значит «считать
          // нечего», как и отсутствие ключа в ответе.
          todo: Array.isArray(s.todo) ? s.todo : [],
          // Комментарий человека к сессии. Единственное поле строки, которого
          // не сказал ни агент, ни трекер: человек пишет его сам, а живёт оно
          // общим списком на машине агрегатора. Пустая строка, а не undefined,
          // — она уходит в стог поиска, и недостающее поле нашлось бы там
          // словом `undefined`.
          comment: typeof s.comment === 'string' ? s.comment : '',
          // Размер сессии — число реплик человека. Поле самой сессии, не
          // записи агента: считает его агрегатор по транскрипту, а не хук, —
          // поэтому и без префикса `agent`.
          promptCount: Number(s.prompts) || 0,
          spec: typeof s.spec === 'string' ? s.spec : '',
          plan: typeof s.plan === 'string' ? s.plan : '',
          agentState: (agent || {}).state || '',
          agentEvent: (agent || {}).event || '',
          // Уведомление агента. Непусто только на attention; у сессии, ждущей
          // разрешения, это единственное, что о ней известно — текста самого
          // вопроса там нет нигде.
          agentMessage: (agent || {}).message || '',
          agentDescription: agentApi.sessionDescription(agent),
          agentPrompt: (agent || {}).prompt || '',
          agentCostUsd: (agent || {}).costUsd || 0,
          agentContextPct: (agent || {}).contextPct || 0,
          // Откуда взялась запись агента: `transcript` — собрана агрегатором
          // из хвоста, пустая строка — написана хуком. Прежде этот же вопрос
          // задавали самому наличию записи, и на машине без хуков её не было
          // вовсе; теперь есть, и спрашивать надо прямо.
          agentSource: (agent || {}).source || '',
          // Начало текущего хода и старт всей сессии. Ноль — «сессия старше
          // появления поля»: колонка возраста тогда откатывается на
          // lastActivity, а строки карточки не печатаются.
          agentTurnAt: (agent || {}).turnAt || 0,
          // started — не про то, кто сейчас работает, а про саму строку: она
          // принадлежит сессии, а не форку, который её на время увёл. Поэтому
          // здесь `s.agent`, а не активный `agent` — единственное поле из
          // четырёх, взятое не у него.
          agentStarted: (s.agent || {}).started || 0,
          // Когда сессия последний раз подавала признаки жизни. Записи агента
          // мало: её пишет хук, а хуков не бывает на Windows вовсе и не бывает
          // у сессии приложения. Такая строка получала ноль, `missingLast`
          // топил её в конец под сортировкой `recent`, а колонка возраста,
          // затемнение старых и карточка молчали — при том что время известно:
          // `mtime` транскрипта агрегатор отдаёт каждой сессии, и строка его
          // уже несёт.
          //
          // Откат, а не замена: у сессии с хуком `updated` точнее — он про
          // событие агента, а не про всякую запись в файле.
          //
          // Чинить это в агрегаторе нельзя: там ноль в `activityAt` значит
          // «хук про сессию не писал», и на этом значении держится выбор между
          // сессиями-тёзками у оконного трекера (`byActivityThen`) — подмени
          // ноль временем файла, и тёзки стали бы сравниваться по нему молча.
          // Ту же подстановку делает у себя `place_order.rs`, и сторожит их
          // общая фикстура.
          lastActivity: agentApi.lastActivityAt(agent) || Number(s.mtime) || 0,
          // «Хук про эту сессию писал» — то же, что раньше значил ненулевой
          // `lastActivity`, пока у того не появился откат на время файла. За
          // это отвечают пункты «Mark seen»/«Mark unread»: отматывать нечего
          // там, где отметок агента нет вовсе.
          //
          // Собранная из хвоста запись сюда не годится, хотя `updated` у неё
          // непустой: это время файла, а не отметка хука. Прежде вопрос решало
          // отсутствие записи целиком, и с её появлением пункты меню включились
          // бы там, где отматывать по-прежнему нечего.
          agentUpdated: (agent || {}).source ? 0 : ((agent || {}).updated || 0),
          // «Человек это видел», а не «не видел»: отрисовщики спрашивают именно
          // так (dotState гасит кружок по agentSeen, карточка печатает
          // «seen: yes»). У сессии без записи агента видеть нечего — там false,
          // и звать она всё равно не будет: и кружок, и текст статуса завязаны
          // на пустой agentState.
          //
          // У записи из хвоста `updated` — время транскрипта, и гашение по нему
          // работает как надо: отметка взгляда, поставленная после последней
          // записи файла, и значит «видел то, что там сейчас». Ноль здесь
          // оставил бы жёлтый вопрос гореть и после захода в сессию.
          agentSeen: agentApi.seenSinceUpdate(agent, focusedAt),
          agentBackground: active.background,
          agentSessionId: active.id,
          // Отметка открытия/взгляда, epoch-секунды: максимум своей (из
          // seen.json) и focusedAt именно этого окна — не всех окон сессии.
          // У карточки с двумя окнами это время своё для каждой.
          focusedAt: focusedAt || 0,
        });
      }
    }
    return rows;
  }

  return { buildSessionList, inDesktopApp, knowsContext };
});
