// Loaded twice: as a <script> in sessions.html and as a module in the tests.
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.OpenTransport = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  // globalThis, а не `root`: тот виден только внешней функции шима, а внутрь
  // factory не передаётся.
  //
  // `normHost` берётся у соседа, а не пишется здесь третьей копией: правило
  // приведения имени машины одно на весь пикер, и разойдись копии — одна и та
  // же машина считалась бы своей в одном месте и чужой в соседнем. Загрузка
  // это выдерживает: session-windows.js стоит в sessions.html раньше (447
  // против 450) и в prepare-frontend.js тоже.
  const windowApi = typeof module === 'object' && module.exports
    ? require('./session-windows')
    : globalThis.SessionWindows;
  const { normHost } = windowApi;

  /**
   * Кто открывает сессию.
   *
   * На машине оконного трекера — он: маппинг проекта на профиль Windows
   * Terminal (`claudeWt.projects`) знает только windows11-manager, и собранная
   * здесь команда `wt.exe` этот профиль теряет. Просьба уходит публикацией в
   * MQTT (`open_session_mqtt`) — тот же транспорт, что уже работает на этой
   * машине для фокуса окна и пометки непрочитанным.
   *
   * Где трекера нет — открываем сами, как раньше: на macOS менеджера не
   * существует, и просьба уехала бы открывать окно на чужой машине.
   *
   * Без брокера MQTT ветка `manager` вела бы Enter в ошибку там, где раньше
   * он открывал терминал локально — регрессия на машине, которой MQTT никогда
   * не был нужен. Поэтому совпадения имени хоста недостаточно: нужен ещё и
   * настроенный брокер, иначе просьбе некуда уйти и остаётся `local`.
   *
   * `windowPid` здесь, в отличие от `canFocus`, не смотрим: право переднего
   * плана нужно для подъёма окна, а не для запуска терминала.
   *
   * Ответ этой функции — про транспорт и только про него. Совпадения хоста
   * мало, чтобы вести туда Enter: строка должна нести настоящий id сессии, и
   * трекер должен эту сессию знать. Обе проверки — в `chooseEnterAction`, и
   * звать на развилке Enter надо её, а не эту.
   *
   * Спрашивает не состояние, а готовый ответ `openManager` из
   * `session-windows.js`: разбор списка трекеров живёт там и только там.
   * Заведись он и здесь — два разбора разошлись бы на первой же правке.
   * Раньше здесь стояло верхнее поле `windowHost`, но с несколькими трекерами
   * оно называет машину с проектными хоткеями, а не машину с менеджером.
   */
  function chooseOpenTransport(manager, configHost, mqttConfigured) {
    const host = normHost((manager || {}).host);
    const mine = normHost(configHost);
    return host && host === mine && mqttConfigured ? 'manager' : 'local';
  }

  /**
   * Виды строк, у которых `id` — это id настоящей сессии.
   *
   * Позитивный список, а не отрицательный: `id` у остальных видов строк —
   * это что-то другое (путь проекта, id снимка), и просьба открыть их на
   * трекере ушла бы искать несуществующую сессию. Перечислены по местам,
   * где строки собираются:
   *  - `session-list.js`: обычная строка сессии — `kind: s.kind || 'interactive'`.
   *    `background` сюда не попадает вовсе: `buildSessionList` отфильтровывает
   *    его раньше, чем строка соберётся, — поля форка достаются строке
   *    родителя через activeAgent, а сам форк своей строки не получает.
   *  - `picker-snapshots.js`: `snapshot-session` — сессия внутри снимка, её
   *    `id` — id той же настоящей сессии, восстановленной или ещё нет;
   *    `snapshot` — заголовок снимка, `id` там — id снимка, не сессии.
   *  - `project-list.js`: `project` — id там путь каталога, сессии ещё нет
   *    вовсе.
   *
   * Deny-list здесь не годится: он остаётся верным только пока кто-то помнит
   * исключить из него каждый новый вид заголовка. Строка неизвестного вида
   * (кто-то добавит новый kind и забудет про этот список) обязана остаться
   * без пункта меню — то же правило, что и у остальных пунктов в
   * `availableActions`: пункт, который не сработает, хуже отсутствующего.
   */
  const SESSION_ID_ROW_KINDS = new Set(['interactive', 'snapshot-session']);

  /**
   * Можно ли предложить строке пункт «Open on <host>».
   *
   * Совмещает три независимых условия: строка несёт настоящий id сессии (иначе
   * приёмник ответит `unknown session` в свой лог, а пикер этого не увидит —
   * PubAck подтверждает публикацию, а не то, что менеджер нашёл сессию),
   * трекер существует, но стоит не на этой машине, и брокер MQTT настроен —
   * без него просьбе некуда уйти, и пункт меню выполнил бы `open_session_mqtt`
   * прямиком в «mqtt не настроен» (main.rs). Пустой `manager.host` проверяется
   * отдельно от `chooseOpenTransport`: та возвращает `'local'` и при пустом
   * хосте (трекера нет вовсе), и пункт в этом случае предлагать тоже нечего —
   * открывать «у себя», когда себя не существует.
   */
  function canOpenRemote(row, manager, configHost, mqttConfigured) {
    if (!row || !SESSION_ID_ROW_KINDS.has(row.kind)) return false;
    if (!manager || !manager.host) return false;
    if (!mqttConfigured) return false;
    return chooseOpenTransport(manager, configHost, mqttConfigured) === 'local';
  }

  /**
   * Знает ли оконный трекер эту сессию.
   *
   * Единственное свидетельство с этой стороны — поле `window`: агрегатор
   * приписывает его только тем сессиям, чей id нашёлся в файле трекера
   * (`ccfzf --state`, `read_windows`), а файл перечисляет окна текущего тика
   * (`buildWindowsFile` в windows11-manager). Приёмник ищет сессию среди своих
   * слотов (`claudeWtSessions` → `state.slots`), а слот есть у каждого окна на
   * экране — значит, `row.window` гарантирует, что просьбу найдут по id.
   *
   * Обратное неверно: слот переживает закрытие окна, и такую сессию менеджер
   * тоже нашёл бы, — но отличить её здесь не от чего. Поэтому строка без
   * `window` доезжает до менеджера не по id, а по каталогу (`rowProjectDir`).
   */
  function trackerKnowsSession(row) {
    return Boolean((row || {}).window);
  }

  /**
   * Каталог проекта строки — то, чем менеджер может открыть незнакомую сессию.
   *
   * Поле `cwd`: `ccfzf --state` кладёт в него каталог из первой строки
   * транскрипта (`dir_cwd`), строка списка несёт его как есть
   * (`session-list.js`: `cwd: s.cwd || ''`, `picker-snapshots.js`: то же поле у
   * сессии снимка). На той стороне по нему работает `profileForCwd`
   * (`claudeWt.projects`) — то есть ровно то, ради чего просьба и уезжает к
   * менеджеру вместо местного `wt.exe`.
   *
   * Пустая строка значит «каталога не знаем»: у сессии, чей транскрипт не
   * прочитался, поле пустое, и просить менеджера было бы не о чем — id он не
   * знает, каталога нет, и просьба умерла бы в его логе молча.
   */
  function rowProjectDir(row) {
    const cwd = (row || {}).cwd;
    return typeof cwd === 'string' ? cwd.trim() : '';
  }

  /**
   * Что делает Enter на строке сессии: 'focus' | 'manager' | 'local'.
   *
   * `strategy` приходит готовой от `chooseOpenStrategy` — второй разбор тех же
   * условий здесь разошёлся бы с первым.
   *
   * Порядок ветвей — не вкусовщина, каждая стоит починенной поломки.
   *
   * `focus` первым — но уже не потому, что только он умеет гасить пикер до
   * публикации и выдавать право на передний план: то и другое делают теперь
   * все четыре ветки, кончающиеся окном (`allow_any_foreground` в main.rs,
   * сторож порядка — `test/hide-before-request.test.js`). Причина осталась
   * одна и простая: подъём открытого окна — это подъём, а не открытие; ветка
   * менеджера заведена ради терминала с нужным профилем.
   *
   * Затем — тот же позитивный список видов строк, что и у `canOpenRemote`:
   * транспорт у них общий, а `id` у остальных видов — путь проекта или id
   * снимка. Полагаться на то, что `choose()` отсеет их раньше, нельзя — список
   * затем и позитивный, чтобы новый вид строки не уехал в `claude-session-open`
   * с чужим id (см. докблок `SESSION_ID_ROW_KINDS`).
   *
   * Затем — по чему менеджер вообще сможет сработать. Ему нужно одно из двух:
   * либо id, который он найдёт среди своих слотов (об этом говорит `window` —
   * см. `trackerKnowsSession`), либо каталог проекта, по которому он откроет
   * терминал с нужным профилем, ничего про сессию не зная (`rowProjectDir`).
   * Строку без того и другого он прочитал бы и записал отказ в свой лог, а
   * пикер об этом не узнал бы: ответа у публикации нет. Такая строка уходит в
   * `local` — так Enter вёл себя до появления этой ветки.
   *
   * И только потом — сам транспорт.
   */
  function chooseEnterAction(row, strategy, manager, configHost, mqttConfigured) {
    if (strategy === 'focus') return 'focus';
    if (!row || !SESSION_ID_ROW_KINDS.has(row.kind)) return 'local';
    if (!trackerKnowsSession(row) && !rowProjectDir(row)) return 'local';
    return chooseOpenTransport(manager, configHost, mqttConfigured);
  }

  /**
   * Кто открывает терминал по каталогу: 'manager' | 'local'.
   *
   * Общая для двух поводов: Enter на строке проекта и «New session» (`^N` и
   * пункт меню) на любой строке. Тела просьб у них разные — `terminal` против
   * `terminal-new`, — а транспорт один, и разводить его значило бы завести две
   * копии правила, которые разойдутся.
   *
   * Позитивного списка видов строк, как у `chooseEnterAction`, здесь нет
   * намеренно: тот список защищает `id` от того, чтобы уехать чужим, а в этих
   * двух просьбах `id` не едет вовсе. Значение имеет только каталог.
   *
   * Пустой каталог оставляет строку местной дороге: без него менеджеру не за
   * что взяться, он записал бы отказ в свой журнал, а пикер об этом не узнал
   * бы — ответа у публикации нет.
   */
  function chooseProjectOpenAction(row, manager, configHost, mqttConfigured) {
    if (!rowProjectDir(row)) return 'local';
    return chooseOpenTransport(manager, configHost, mqttConfigured);
  }

  return {
    chooseOpenTransport, canOpenRemote, chooseEnterAction, rowProjectDir,
    chooseProjectOpenAction,
  };
});
